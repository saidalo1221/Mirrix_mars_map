import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {once} from 'node:events';
import {pathToFileURL} from 'node:url';
import {createAppServer} from '../scripts/serve.mjs';

const [, , modulePath, executablePath, screenshotDirectory] = process.argv;
const {chromium} = await import(modulePath ? pathToFileURL(modulePath).href : 'playwright');
const server = createAppServer().listen(0, '127.0.0.1');
await once(server, 'listening');
const base = `http://127.0.0.1:${server.address().port}`;
async function selectCoordinates(page, value) {
  await page.locator('#search').fill(value);
  await page.locator('#search').press('Enter');
}
let browser;
try {
  browser = await chromium.launch({executablePath, args:['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--no-first-run']});
  const page = await browser.newPage({viewport:{width:1440,height:960}, acceptDownloads:true});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => {
    if (response.url().startsWith(base) && response.status() >= 400) errors.push(`${response.status()} ${response.url()}`);
  });
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('NASA'));
  await page.waitForFunction(() => document.querySelector('#elevation-value').textContent.includes(' m'));
  assert.equal(await page.locator('#map-heading').textContent(), 'Mars globe');
  const surface = page.locator('#surface');
  const rect = await surface.boundingBox();
  const center = [rect.x + rect.width / 2, rect.y + rect.height / 2];
  await page.mouse.move(...center);
  await page.mouse.down();
  await page.mouse.move(center[0] + 95, center[1] + 40, {steps:8});
  await page.mouse.move(rect.x + rect.width + 56, rect.y + 45, {steps:8});
  await page.mouse.up();
  assert.equal(await page.evaluate(() => window.getSelection().toString()), '');
  assert.equal(await surface.evaluate(element => getComputedStyle(element).userSelect), 'none');
  await page.mouse.wheel(0, -120);
  await surface.click({position:{x:rect.width/2,y:rect.height/2}});
  assert.equal(await page.locator('#location-title').textContent(), 'Selected coordinates');
  await page.getByLabel('Jump to a place').selectOption('landmark:jezero');
  await page.waitForTimeout(480);
  if (screenshotDirectory) await page.screenshot({path:`${screenshotDirectory}/ares-globe.png`});
  const oldLayer = await page.locator('#layer-credit').textContent();
  await page.locator('#layer').selectOption({index:1});
  await page.waitForFunction(old => document.querySelector('#layer-credit').textContent !== old && !document.querySelector('#map-message').textContent, oldLayer);
  await page.getByRole('button', {name:'2D map'}).click();
  assert.equal(await page.locator('#map-heading').textContent(), 'Mars map');
  assert.equal(await page.locator('#location-title').textContent(), 'Jezero Crater');
  assert.equal(await page.locator('#demo, #field-open').count(), 0);
  assert.equal(await page.locator('.terrain-coverage, #find-terrain').count(), 0);
  await page.getByRole('button', {name:'Center map on selected point'}).click();
  await selectCoordinates(page, '18.4608, 77.4065');
  await page.getByRole('button', {name:'Set destination'}).click();
  await page.locator('#plan:enabled').waitFor();
  assert.equal(await page.locator('.route-card').count(), 0);
  await page.getByRole('button', {name:'Generate routes'}).click();
  await page.waitForFunction(() => document.querySelectorAll('.route-card').length > 0);
  assert.equal(await page.locator('#region').inputValue(), 'jezero');
  assert.match(await page.locator('#end-value').textContent(), /18.4608/);
  await selectCoordinates(page, '18.4446, 77.4509');
  await page.getByRole('button', {name:'Set start'}).click();
  await selectCoordinates(page, '18.449, 77.4135');
  await page.getByRole('button', {name:'Add science stop'}).click();
  await page.getByRole('textbox', {name:'Observation objective'}).fill('Inspect layering');
  await page.getByRole('textbox', {name:'Observation objective'}).press('Tab');
  await selectCoordinates(page, '18.4608, 77.4065');
  await page.getByRole('button', {name:'Set destination'}).click();
  await page.locator('#plan:enabled').waitFor();
  assert.equal(await page.locator('.route-card').count(), 0);
  assert.match(await page.locator('#start-value').textContent(), /18.4446/);
  await page.waitForFunction(() => document.querySelector('#map-heading').textContent === 'Regional terrain');
  await page.waitForFunction(() => document.querySelector('#elevation-source').textContent.includes('20 m'));
  assert.match(await page.getByRole('textbox', {name:'Observation objective'}).inputValue(), /layering/);
  await page.getByRole('button', {name:'Optical', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('HiRISE'));
  await page.getByRole('button', {name:'Thermal IR', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('THEMIS'));
  assert.match(await page.locator('#regional-science-note').textContent(), /temperature.*unavailable/i);
  await page.getByRole('button', {name:'Topography', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#map-kind').textContent.includes('TOPOGRAPHY'));
  await page.getByRole('button', {name:'Generate routes'}).click();
  await page.waitForFunction(() => document.querySelectorAll('.route-card').length >= 2);
  assert.match(await page.locator('#recommendation').textContent(), /balanced mission/i);
  assert.match(await page.locator('#routes').textContent(), /Within budgets/);
  assert.equal(await page.locator('#profile svg').count(), 1);
  await page.getByRole('button', {name:'Toggle fullscreen'}).click();
  await page.waitForFunction(() => document.fullscreenElement?.id === 'planning-workspace' ||
    document.querySelector('#planning-workspace').classList.contains('fullscreen-fallback'));
  assert.equal(await page.getByRole('button', {name:'Set start', exact:true}).isEnabled(), true);
  assert.equal(await page.getByRole('button', {name:'Set destination', exact:true}).isEnabled(), true);
  assert.equal(await page.locator('#profile svg').isVisible(), true);
  assert.ok(await page.locator('.inspector').evaluate((el) =>
    el.getBoundingClientRect().left > document.querySelector('.map-column').getBoundingClientRect().left));
  await page.getByRole('button', {name:'Toggle fullscreen'}).click();
  await page.locator('#routes .route-card').nth(1).click();
  assert.match(await page.locator('#profile-meta').textContent(), /Route B/);
  await page.getByRole('slider', {name:'Traverse progress'}).focus();
  await page.keyboard.press('End');
  assert.match(await page.locator('#progress-value').textContent(), /km/);
  await page.getByRole('button', {name:'2D map'}).click();
  assert.match(await page.locator('#profile-meta').textContent(), /Route B/);
  await page.getByRole('button', {name:'Terrain', exact:true}).click();
  await page.getByText('Equipment assumptions', {exact:true}).click();
  await page.locator('#equipmentMinutes').fill('110');
  await page.locator('#reserveMinutes').fill('15');
  await page.locator('#objective').selectOption('science');
  await page.getByRole('button', {name:'Generate routes'}).click();
  await page.waitForFunction(() => document.querySelector('#recommendation').textContent.includes('science coverage'));
  await page.getByRole('button', {name:'Thermal IR', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('THEMIS'));
  await page.getByRole('slider', {name:'Traverse progress'}).focus();
  await page.keyboard.press('End');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', {name:'Export JSON'}).click();
  const download = await downloadEvent;
  const report = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(report.region.id, 'jezero');
  assert.match(report.regionalImagery.name, /HiRISE/);
  assert.match(report.thermalImagery.name, /THEMIS/);
  assert.equal(report.activeRegionalLayer, 'thermal');
  assert.equal(report.equipmentUsableMinutes, 95);
  assert.equal(report.fieldSimulation.distanceRemainingMeters, 0);
  assert.equal(report.routes[0].stops.length, 1);
  assert.ok(report.routes[0].geometry.coordinates.length > 40);
  await page.evaluate(() => { window.print = () => { window.printInvoked = true; }; });
  await page.getByRole('button', {name:'Print report'}).click();
  assert.equal(await page.evaluate(() => window.printInvoked), true);
  assert.match(await page.locator('#print-report').textContent(), /Sources and assumptions/);
  if (screenshotDirectory) await page.screenshot({path:`${screenshotDirectory}/ares-jezero.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.getByRole('button', {name:'Data sources'}).click();
  assert.equal(await page.locator('#sources').isVisible(), true);
  assert.equal(await page.getByRole('link', {name:'USGS HiRISE terrain archive'}).count(), 1);
  assert.equal(await page.getByRole('link', {name:'USGS CTX terrain archive'}).count(), 1);
  await page.getByRole('button', {name:'Close data sources'}).click();
  await page.getByLabel('Jump to a place').selectOption('gale');
  await page.waitForFunction(() => document.querySelector('#region-detail').textContent.includes('10.1 m'));
  await page.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('Murray Lab'));
  assert.equal(await page.getByRole('button', {name:'Optical', exact:true}).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.getByRole('button', {name:'Thermal IR', exact:true}).isEnabled(), false);
  await page.getByRole('button', {name:'Topography', exact:true}).click();
  assert.match(await page.locator('#regional-science-note').textContent(), /thermal overlay unavailable/i);
  assert.deepEqual(errors, []);

  const fallback = await browser.newPage();
  await fallback.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (kind, ...args) {
      return kind === 'webgl' ? null : original.call(this, kind, ...args);
    };
  });
  await fallback.goto(base);
  await fallback.waitForFunction(() => document.querySelector('#map-heading').textContent === 'Mars map');
  await selectCoordinates(fallback, '18.4608, 77.4065');
  await fallback.getByRole('button', {name:'Set destination'}).click();
  await fallback.getByRole('button', {name:'Thermal IR', exact:true}).click();
  await fallback.waitForFunction(() => document.querySelector('#layer-credit').textContent.includes('THEMIS'));
  await fallback.getByRole('button', {name:'Generate routes'}).click();
  await fallback.waitForFunction(() => document.querySelectorAll('.route-card').length >= 2);
  console.log('Chromium browser smoke passed: globe, three Jezero layers, equipment limits, destination setup, manual routing, export, mobile and 2D fallback.');
} finally {
  await browser?.close();
  server.close();
}
